    public static class Files
    {
        public static readonly JavaScriptSerializer Json = new JavaScriptSerializer();
        public static T Load<T>(string path) where T : new()
        { return File.Exists(path) ? Json.Deserialize<T>(File.ReadAllText(path, Encoding.UTF8)) : new T(); }
        public static void Save(string path, object value)
        {
            string temporary = path + ".tmp";
            File.WriteAllText(temporary, Json.Serialize(value), new UTF8Encoding(false));
            if (File.Exists(path)) File.Replace(temporary, path, null);
            else File.Move(temporary, path);
        }
        public static string Hash(string text)
        {
            using (var sha = SHA256.Create())
                return BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(text))).Replace("-", "").Substring(0, 16).ToLowerInvariant();
        }
        public static bool IsManagedImage(string path)
        { return Regex.IsMatch(Path.GetFileName(path), @"^bing-\d{8}-[a-f0-9]{16}(-[a-f0-9]{32})?\.jpg$"); }
        public static void ValidateImage(string path)
        {
            using (var image = Image.FromFile(path))
                if (image.Width < 640 || image.Height < 360 || image.Width > 16000 || image.Height > 16000)
                    throw new InvalidDataException("Unexpected image dimensions.");
        }
        public static void Cleanup(string directory, string current, int keep)
        {
            // Only names generated by this program, and only this exact folder. Never recurse.
            var old = new DirectoryInfo(directory).GetFiles("bing-*.jpg", SearchOption.TopDirectoryOnly)
                .Where(f => IsManagedImage(f.Name) && !f.Attributes.HasFlag(FileAttributes.ReparsePoint)
                    && !string.Equals(f.FullName, current, StringComparison.OrdinalIgnoreCase))
                .OrderByDescending(f => f.LastWriteTimeUtc).Skip(keep - 1);
            foreach (var file in old) file.Delete();
        }
    }

    internal static class WindowsImages
    {
        [DllImport("user32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
        private static extern bool SystemParametersInfo(uint action, uint parameter, string value, uint flags);

        private static Type RuntimeType(string name, string assembly)
        { return Type.GetType(name + ", " + assembly + ", ContentType=WindowsRuntime", true); }

        private static object Wait(object operation, Type resultType)
        {
            var extensions = Assembly.Load("System.Runtime.WindowsRuntime, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089")
                .GetType("System.WindowsRuntimeSystemExtensions");
            var method = resultType == null
                ? extensions.GetMethods().Single(m => m.Name == "AsTask" && !m.IsGenericMethod
                    && m.GetParameters().Length == 1 && m.GetParameters()[0].ParameterType.Name == "IAsyncAction")
                : extensions.GetMethods().Single(m => m.Name == "AsTask" && m.IsGenericMethodDefinition
                    && m.GetGenericArguments().Length == 1 && m.GetParameters().Length == 1
                    && m.GetParameters()[0].ParameterType.Name == "IAsyncOperation`1").MakeGenericMethod(resultType);
            var task = (Task)method.Invoke(null, new[] { operation });
            if (!task.Wait(45000)) throw new TimeoutException("Windows personalization timed out.");
            return resultType == null ? null : task.GetType().GetProperty("Result").GetValue(task, null);
        }

        public static void SetDesktop(string path)
        {
            using (var key = Registry.CurrentUser.OpenSubKey(@"Control Panel\Desktop", true))
            { key.SetValue("WallpaperStyle", "10"); key.SetValue("TileWallpaper", "0"); }
            // Switch from slideshow/Windows Spotlight to a picture for this user.
            using (var key = Registry.CurrentUser.CreateSubKey(@"Software\Microsoft\Windows\CurrentVersion\Explorer\Wallpapers"))
                key.SetValue("BackgroundType", 0, RegistryValueKind.DWord);
            if (!SystemParametersInfo(0x0014, 0, path, 0x0001 | 0x0002))
                throw new Win32Exception(Marshal.GetLastWin32Error());
        }

        public static string CurrentLockScreen()
        {
            var type = RuntimeType("Windows.System.UserProfile.LockScreen", "Windows.System.UserProfile");
            var uri = type.GetProperty("OriginalImageFile").GetValue(null, null) as Uri;
            return uri != null && uri.IsFile ? uri.LocalPath : "";
        }

        public static void SetLockScreen(string path)
        {
            // Use LockScreen directly: TrySetLockScreenImageAsync can return false for unpackaged desktop apps.
            var type = RuntimeType("Windows.System.UserProfile.LockScreen", "Windows.System.UserProfile");
            var storageType = RuntimeType("Windows.Storage.StorageFile", "Windows.Storage");
            var file = Wait(storageType.GetMethod("GetFileFromPathAsync").Invoke(null, new object[] { path }), storageType);
            using (var key = Registry.CurrentUser.CreateSubKey(@"Software\Microsoft\Windows\CurrentVersion\ContentDeliveryManager"))
                key.SetValue("RotatingLockScreenEnabled", 0, RegistryValueKind.DWord);
            using (var key = Registry.CurrentUser.CreateSubKey(@"Software\Microsoft\Windows\CurrentVersion\Lock Screen"))
                key.SetValue("SlideshowEnabled", 0, RegistryValueKind.DWord);
            Wait(type.GetMethod("SetImageFileAsync").Invoke(null, new[] { file }), null);
            if (!string.Equals(CurrentLockScreen(), path, StringComparison.OrdinalIgnoreCase))
                throw new InvalidOperationException("Windows did not persist the lock screen image.");
        }
    }

    internal static class Network
    {
        public static Uri BingUri(string value)
        {
            var uri = new Uri(value, UriKind.Absolute);
            if (uri.Scheme != "https" || !(uri.Host.Equals("bing.com", StringComparison.OrdinalIgnoreCase)
                || uri.Host.EndsWith(".bing.com", StringComparison.OrdinalIgnoreCase)))
                throw new InvalidDataException("Image URL is not an HTTPS Bing URL.");
            return uri;
        }
        public static void Download(Uri uri, Stream output, int limit)
        {
            var request = (HttpWebRequest)WebRequest.Create(BingUri(uri.AbsoluteUri));
            request.Timeout = 25000;
            request.ReadWriteTimeout = 25000;
            request.UserAgent = "BingWallpaperLite/1.0";
            request.CachePolicy = new System.Net.Cache.RequestCachePolicy(System.Net.Cache.RequestCacheLevel.NoCacheNoStore);
            using (var response = (HttpWebResponse)request.GetResponse())
            {
                BingUri(response.ResponseUri.AbsoluteUri);
                if (response.ContentLength > limit) throw new InvalidDataException("Download exceeds size limit.");
                using (var input = response.GetResponseStream())
                {
                    var buffer = new byte[65536];
                    int total = 0, count;
                    while ((count = input.Read(buffer, 0, buffer.Length)) != 0)
                    {
                        total += count;
                        if (total > limit) throw new InvalidDataException("Download exceeds size limit.");
                        output.Write(buffer, 0, count);
                    }
                }
            }
        }
        public static BingImage Today(Configuration config)
        {
            Exception last = null;
            foreach (string host in new[] { "www.bing.com", "cn.bing.com" })
            {
                try
                {
                    using (var memory = new MemoryStream())
                    {
                        Download(new Uri("https://" + host + "/HPImageArchive.aspx?format=js&idx=0&n=1&mkt=" + config.Market), memory, 1024 * 1024);
                        var data = Files.Json.Deserialize<BingResponse>(Encoding.UTF8.GetString(memory.ToArray()));
                        if (data == null || data.images == null || data.images.Length == 0) throw new InvalidDataException("Bing returned no images.");
                        var image = data.images[0];
                        if (!Regex.IsMatch(image.startdate ?? "", @"^\d{8}$") || string.IsNullOrEmpty(image.urlbase)
                            || !image.urlbase.StartsWith("/th?id=OHR.", StringComparison.Ordinal))
                            throw new InvalidDataException("Invalid Bing metadata.");
                        return image;
                    }
                }
                catch (Exception error) { last = error; }
            }
            throw new IOException("Cannot get Bing image metadata.", last);
        }
    }

    internal static class WallpaperWorker
    {
        private static string root;
        private static void Log(string text)
        {
            string path = Path.Combine(root, "update.log");
            if (File.Exists(path) && new FileInfo(path).Length > 256 * 1024)
            { if (File.Exists(path + ".1")) File.Delete(path + ".1"); File.Move(path, path + ".1"); }
            File.AppendAllText(path, DateTimeOffset.Now.ToString("o") + " " + text + Environment.NewLine, Encoding.UTF8);
        }

        [STAThread]
        public static int Main(string[] args)
        {
            root = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "BingWallpaperLite");
            int index = Array.IndexOf(args, "--data-dir");
            if (index >= 0)
            {
                if (index + 1 >= args.Length) return 2;
                root = Path.GetFullPath(args[index + 1]);
            }
            Directory.CreateDirectory(root);
            return ExecuteUpdate(args.Contains("--force"), args.Contains("--download-only"));
        }

        internal static int ExecuteUpdate(bool force, bool downloadOnly)
        {
            using (var mutex = new Mutex(false, @"Local\BingWallpaperLite-" + Files.Hash(root.ToLowerInvariant())))
            {
                bool acquired;
                try { acquired = mutex.WaitOne(0); }
                catch (AbandonedMutexException) { acquired = true; }
                if (!acquired) return 0;
                try { return Update(force, downloadOnly); }
                catch (Exception error)
                {
                    try { Log("ERROR " + error); } catch { }
                    return 1;
                }
                finally { mutex.ReleaseMutex(); }
            }
        }

        private static int Update(bool force, bool downloadOnly)
        {
            ServicePointManager.SecurityProtocol = SecurityProtocolType.Tls12;
            var config = Files.Load<Configuration>(Path.Combine(root, "config.json"));
            config.Validate();
            string images = Path.Combine(root, "images");
            Directory.CreateDirectory(images);
            string statePath = Path.Combine(root, "state.json");
            var state = Files.Load<UpdateState>(statePath);
            string temporary = null;
            try
            {
                foreach (var stale in new DirectoryInfo(images).GetFiles("download-*.tmp"))
                    if (Regex.IsMatch(stale.Name, @"^download-[a-f0-9]{32}\.tmp$") && stale.LastWriteTimeUtc < DateTime.UtcNow.AddDays(-1)
                        && !stale.Attributes.HasFlag(FileAttributes.ReparsePoint)) stale.Delete();

                var image = Network.Today(config);
                string url = "https://www.bing.com" + image.urlbase + "_" + config.Resolution + ".jpg";
                string filename = "bing-" + image.startdate + "-" + Files.Hash(url + config.Market);
                string path = Path.Combine(images, filename + ".jpg");
                if (state.SourceUrl == url && !string.IsNullOrEmpty(state.LockScreenImage)
                    && string.Equals(Path.GetDirectoryName(state.LockScreenImage), images, StringComparison.OrdinalIgnoreCase)
                    && Path.GetFileName(state.LockScreenImage).StartsWith(filename, StringComparison.Ordinal)
                    && Files.IsManagedImage(state.LockScreenImage) && File.Exists(state.LockScreenImage))
                    path = state.LockScreenImage;
                if (File.Exists(path))
                {
                    try { Files.ValidateImage(path); }
                    catch { path = Path.Combine(images, filename + "-" + Guid.NewGuid().ToString("N") + ".jpg"); }
                }
                bool lockCurrent = false;
                if (!downloadOnly)
                {
                    try { lockCurrent = string.Equals(WindowsImages.CurrentLockScreen(), path, StringComparison.OrdinalIgnoreCase); }
                    catch (Exception error) { Log("Cannot inspect current lock screen: " + error.Message); }
                    // WinRT requires a new filename when reapplying an image.
                    if (File.Exists(path) && (force || !lockCurrent))
                    {
                        string copy = Path.Combine(images, filename + "-" + Guid.NewGuid().ToString("N") + ".jpg");
                        File.Copy(path, copy);
                        path = copy;
                        lockCurrent = false;
                    }
                }
                if (!File.Exists(path))
                {
                    temporary = Path.Combine(images, "download-" + Guid.NewGuid().ToString("N") + ".tmp");
                    Exception last = null;
                    foreach (string host in new[] { "www.bing.com", "cn.bing.com" })
                    {
                        try
                        {
                            using (var output = new FileStream(temporary, FileMode.Create, FileAccess.Write))
                                Network.Download(new Uri(url.Replace("www.bing.com", host)), output, 30 * 1024 * 1024);
                            Files.ValidateImage(temporary);
                            last = null;
                            break;
                        }
                        catch (Exception error) { last = error; }
                    }
                    if (last != null) throw new IOException("Cannot download a valid Bing image.", last);
                    File.Move(temporary, path);
                    temporary = null;
                    Log("Downloaded " + path);
                }
                if (downloadOnly)
                {
                    Files.Save(Path.Combine(root, "download-check.json"), new { Image = path, Date = image.startdate, Title = image.title, Url = url });
                    Log("Download check OK; Windows settings unchanged.");
                    return 0;
                }

                state.LastAttempt = DateTimeOffset.Now.ToString("o");
                WindowsImages.SetDesktop(path);
                state.DesktopImage = path;
                Files.Save(statePath, state);
                if (!lockCurrent) WindowsImages.SetLockScreen(path);
                state.LockScreenImage = path;
                state.ImageDate = image.startdate;
                state.Title = image.title;
                state.Copyright = image.copyright;
                state.SourceUrl = url;
                state.LastSuccess = DateTimeOffset.Now.ToString("o");
                state.LastError = null;
                Files.Save(statePath, state);
                // Keep all previous images if either Windows setting or state persistence failed.
                Files.Cleanup(images, path, config.KeepImages);
                Log("OK desktop + lock screen: " + image.startdate + " " + image.title);
                return 0;
            }
            catch (Exception error)
            {
                if (!downloadOnly)
                {
                    state.LastAttempt = DateTimeOffset.Now.ToString("o");
                    state.LastError = error.GetBaseException().Message;
                    Files.Save(statePath, state);
                }
                throw;
            }
            finally
            {
                if (temporary != null && File.Exists(temporary)) File.Delete(temporary);
            }
        }
    }
